-- I-ITSM baseline schema. Users use single-table inheritance (discriminator column: role).

CREATE TABLE teams (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(100) NOT NULL UNIQUE,
    lead_id     BIGINT,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role             VARCHAR(30) NOT NULL
                     CHECK (role IN ('EMPLOYEE','TECHNICIAN','TEAM_LEAD','ADMINISTRATOR','IT_MANAGER')),
    email            VARCHAR(150) NOT NULL UNIQUE,
    password_hash    VARCHAR(100) NOT NULL,
    full_name        VARCHAR(120) NOT NULL,
    active           BOOLEAN NOT NULL DEFAULT TRUE,
    -- Employee columns
    department       VARCHAR(100),
    -- Technician / TeamLead columns (NULL for other roles)
    team_id          BIGINT REFERENCES teams(id),
    max_workload     INT CHECK (max_workload IS NULL OR max_workload > 0),
    available        BOOLEAN,
    experience_years INT CHECK (experience_years IS NULL OR experience_years >= 0),
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_users_role ON users(role);
CREATE INDEX idx_users_team ON users(team_id);

ALTER TABLE teams ADD CONSTRAINT fk_teams_lead FOREIGN KEY (lead_id) REFERENCES users(id);

CREATE TABLE skills (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE technician_skills (
    technician_id BIGINT NOT NULL REFERENCES users(id),
    skill_id      BIGINT NOT NULL REFERENCES skills(id),
    proficiency   SMALLINT NOT NULL CHECK (proficiency BETWEEN 1 AND 5),
    PRIMARY KEY (technician_id, skill_id)
);

CREATE TABLE categories (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              VARCHAR(80) NOT NULL UNIQUE,
    description       VARCHAR(255),
    keywords          TEXT NOT NULL DEFAULT '',       -- comma-separated, used by auto-categorization
    required_skill_id BIGINT REFERENCES skills(id),
    active            BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE it_services (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  VARCHAR(120) NOT NULL UNIQUE,
    description           VARCHAR(255),
    business_criticality  SMALLINT NOT NULL CHECK (business_criticality BETWEEN 1 AND 5),
    active                BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE sla_policies (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    priority           VARCHAR(2) NOT NULL CHECK (priority IN ('P1','P2','P3','P4')),
    service_id         BIGINT REFERENCES it_services(id),   -- NULL = default policy for the priority
    response_minutes   INT NOT NULL CHECK (response_minutes > 0),
    resolution_minutes INT NOT NULL CHECK (resolution_minutes > 0)
);
CREATE UNIQUE INDEX uq_sla_default ON sla_policies(priority) WHERE service_id IS NULL;
CREATE UNIQUE INDEX uq_sla_service ON sla_policies(priority, service_id) WHERE service_id IS NOT NULL;

CREATE TABLE incidents (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_number      VARCHAR(20) NOT NULL UNIQUE,           -- e.g. INC1024
    title                VARCHAR(200) NOT NULL,
    description          TEXT NOT NULL,
    reporter_id          BIGINT NOT NULL REFERENCES users(id),
    category_id          BIGINT REFERENCES categories(id),
    service_id           BIGINT NOT NULL REFERENCES it_services(id),
    assignee_id          BIGINT REFERENCES users(id),
    impact               SMALLINT NOT NULL CHECK (impact BETWEEN 1 AND 3),
    urgency              SMALLINT NOT NULL CHECK (urgency BETWEEN 1 AND 3),
    affected_users       INT NOT NULL DEFAULT 1 CHECK (affected_users >= 1),
    priority_score       INT,
    priority             VARCHAR(2) CHECK (priority IN ('P1','P2','P3','P4')),
    status               VARCHAR(20) NOT NULL DEFAULT 'NEW'
                         CHECK (status IN ('NEW','CLASSIFIED','ASSIGNED','ACKNOWLEDGED','IN_PROGRESS',
                                           'PENDING_INFO','RESOLVED','VERIFIED','CLOSED','CANCELLED','DUPLICATE')),
    sla_status           VARCHAR(10) NOT NULL DEFAULT 'ON_TRACK'
                         CHECK (sla_status IN ('ON_TRACK','AT_RISK','VIOLATED')),
    response_deadline    TIMESTAMPTZ,
    resolution_deadline  TIMESTAMPTZ,
    sla_paused_at        TIMESTAMPTZ,
    sla_paused_seconds   BIGINT NOT NULL DEFAULT 0,
    escalation_level     SMALLINT NOT NULL DEFAULT 0,
    duplicate_of_id      BIGINT REFERENCES incidents(id),
    resolution           TEXT,
    responded_at         TIMESTAMPTZ,
    resolved_at          TIMESTAMPTZ,
    closed_at            TIMESTAMPTZ,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_incidents_status   ON incidents(status);
CREATE INDEX idx_incidents_priority ON incidents(priority);
CREATE INDEX idx_incidents_assignee ON incidents(assignee_id);
CREATE INDEX idx_incidents_reporter ON incidents(reporter_id);
CREATE INDEX idx_incidents_service  ON incidents(service_id);
CREATE INDEX idx_incidents_sla      ON incidents(sla_status);
CREATE INDEX idx_incidents_created  ON incidents(created_at);

CREATE TABLE incident_comments (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id  BIGINT NOT NULL REFERENCES incidents(id),
    author_id    BIGINT NOT NULL REFERENCES users(id),
    type         VARCHAR(20) NOT NULL CHECK (type IN ('NOTE','INFO_REQUEST','INFO_RESPONSE')),
    body         TEXT NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_comments_incident ON incident_comments(incident_id);

CREATE TABLE audit_logs (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id     BIGINT REFERENCES incidents(id),
    user_id         BIGINT REFERENCES users(id),        -- NULL = performed by the system
    action          VARCHAR(60) NOT NULL,
    previous_state  VARCHAR(20),
    new_state       VARCHAR(20),
    description     TEXT,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_audit_incident ON audit_logs(incident_id);

-- Audit trail is append-only: block UPDATE and DELETE at the database level.
CREATE FUNCTION audit_logs_immutable() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'audit_logs is append-only';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_logs_immutable
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION audit_logs_immutable();

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users(id),
    incident_id  BIGINT REFERENCES incidents(id),
    event_type   VARCHAR(40) NOT NULL,
    message      VARCHAR(500) NOT NULL,
    is_read      BOOLEAN NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX idx_notifications_user ON notifications(user_id, is_read);

CREATE TABLE feedback (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    incident_id  BIGINT NOT NULL UNIQUE REFERENCES incidents(id),
    rating       SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comments     TEXT,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE system_config (
    config_key    VARCHAR(80) PRIMARY KEY,
    config_value  VARCHAR(255) NOT NULL,
    description   VARCHAR(255)
);
