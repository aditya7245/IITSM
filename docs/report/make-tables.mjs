// Builds the LaTeX pieces of the report that come from other files, so the report never disagrees with them:
//   generated/testcases.tex  from docs/TEST_CASES.md
// and copies the screenshots used by the report into docs/screenshots/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DOCS = path.resolve(HERE, '..');
const ROOT = path.resolve(DOCS, '..');
fs.mkdirSync(path.join(HERE, 'generated'), { recursive: true });

const tex = (s) => s
  .replace(/\\/g, '\\textbackslash{}')
  .replace(/([&%$#_{}])/g, '\\$1')
  .replace(/~/g, '\\textasciitilde{}')
  .replace(/\^/g, '\\textasciicircum{}');
const md = (s) => tex(s)
  .replace(/`([^`]+)`/g, (_, c) => `\\texttt{${c}}`)
  .replace(/\*\*([^*]+)\*\*/g, '\\textbf{$1}');
// test names: let LaTeX break before capitals and after '#'
const testName = (s) => `\\texttt{\\footnotesize ${tex(s).replace(/\\#/g, '\\#\\allowbreak{}').replace(/([a-z])([A-Z])/g, '$1\\allowbreak{}$2')}}`;

const rows = fs.readFileSync(path.join(DOCS, 'TEST_CASES.md'), 'utf8').split(/\r?\n/)
  .filter((l) => /^\| TC-\d+/.test(l))
  .map((l) => l.split('|').slice(1, -1).map((c) => c.trim()));
const body = rows.map(([id, cat, steps, expected, tests]) => {
  const names = tests.replace(/`/g, '').split('<br>').map((t) => testName(t.trim())).join('\\newline ');
  return `${id} & ${tex(cat)} & ${md(steps)} & ${md(expected)} & ${names} \\\\ \\midrule`;
}).join('\n');
fs.writeFileSync(path.join(HERE, 'generated', 'testcases.tex'), `% generated by make-tables.mjs from docs/TEST_CASES.md
\\begin{longtable}{@{}L{1.0cm}L{1.6cm}L{4.0cm}L{4.2cm}L{4.6cm}@{}}
\\toprule
\\textbf{ID} & \\textbf{Category} & \\textbf{Steps} & \\textbf{Expected result} & \\textbf{Automated test} \\\\ \\midrule
\\endhead
${body}
\\end{longtable}
`);
console.log(`${rows.length} test cases`);

// The code excerpts (generated/code/*.java) and the screenshots (docs/screenshots) are committed. They are only
// refreshed when the local, not-committed video/ folder exists.
const VIDEO = path.join(ROOT, 'video');
if (!fs.existsSync(VIDEO)) {
  console.log('video/ not present: keeping the committed code excerpts and screenshots');
  process.exit(0);
}

const code = JSON.parse(fs.readFileSync(path.join(VIDEO, 'src', 'generated', 'code.json'), 'utf8'));
fs.mkdirSync(path.join(HERE, 'generated', 'code'), { recursive: true });
for (const [key, { file, code: text }] of Object.entries(code)) {
  fs.writeFileSync(path.join(HERE, 'generated', 'code', `${key}.java`), `// ${file}\n${text.replace(/…/g, '...')}\n`);
}
console.log(`${Object.keys(code).length} code excerpts`);

const SHOTS = ['login', 'w1-filled', 'w1-created', 'w1-detail', 'w1-emp-bell', 'w1-tech-work', 'w2-pending', 'w2-history',
  'w2-feedback', 'w3-duplicates', 'w3-escalated', 'w3-recommend', 'w3-mailpit', 'a-dashboard', 'a-dashboard-charts', 'a-search-filtered',
  'a-audit', 'a-technician-skills', 'a-settings', 'a-sla', 'swagger', 'a-dashboard-dark'];
const dest = path.join(DOCS, 'screenshots');
fs.mkdirSync(dest, { recursive: true });
for (const s of SHOTS) fs.copyFileSync(path.join(VIDEO, 'public', 'shots', `${s}.png`), path.join(dest, `${s}.png`));
console.log(`${SHOTS.length} screenshots copied`);
